// Author: Adam "tick" Pielak, https://wazuh.blog
// Wazuh agent by Zabbix agent / Zabbix agent active (Linux).
// Data source: wazuh-agentd state file
// (https://documentation.wazuh.com/current/user-manual/reference/statistics-files/wazuh-agentd-state.html),
// VERSION.json and the process list.

import { heartbeat, js, jsonpath, perSecond, regex, type ItemDef, type TemplateDef, type TriggerDef } from "./lib.ts";

export const AGENT = "Wazuh agent by Zabbix agent";
export const AGENT_ACTIVE = "Wazuh agent by Zabbix agent active";

const STATE = "vfs.file.contents[{$WAZUH.AGENT.HOME}/var/run/wazuh-agentd.state]";
const VERSION = "vfs.file.contents[{$WAZUH.AGENT.HOME}/VERSION.json]";
const STATE_TIME = "vfs.file.time[{$WAZUH.AGENT.HOME}/var/run/wazuh-agentd.state,modify]";
const DAEMONS = ["wazuh-agentd", "wazuh-execd", "wazuh-logcollector", "wazuh-modulesd", "wazuh-syscheckd"];

const field = (name: string) => `${name}='([^']*)'`;

function build(name: string, type: string | undefined): TemplateDef {
  const T = name;
  const dep = (n: string, key: string, description: string, component: string, o: Partial<ItemDef>): ItemDef => ({
    name: n,
    key,
    type: "DEPENDENT",
    master: STATE,
    description,
    tags: [["component", component]],
    ...o,
  });

  const items: ItemDef[] = [
    ...DAEMONS.map(
      (d): ItemDef => ({
        name: `Process [${d}]: Number of processes`,
        key: `proc.num[${d}]`,
        type,
        delay: "1m",
        description: `Number of running ${d} processes.`,
        tags: [["component", "system"], ["process", d]],
      }),
    ),
    {
      name: "Get state",
      key: STATE,
      type,
      delay: "1m",
      history: "0",
      value_type: "TEXT",
      description: "Contents of the wazuh-agentd state file. wazuh-agentd rewrites the file every 5 seconds by default (agent.state_interval in internal_options.conf).",
      tags: [["component", "raw"]],
    },
    {
      name: "State file modification time",
      key: STATE_TIME,
      type,
      delay: "1m",
      units: "unixtime",
      description: "Last modification time of the wazuh-agentd state file. A file that is no longer updated means wazuh-agentd is stopped or hung.",
      tags: [["component", "health"]],
    },
    dep("Connection status", "wazuh.agent.status", "Connection status of the agent: connected - connection established with the manager in the last 10 seconds, disconnected - no ACK in the last 60 seconds, pending - waiting for the connection.", "health", {
      valuemap: "Wazuh agent status",
      preprocessing: [
        js(`var match = value.match(/^status='([^']*)'$/m),
	states = {disconnected: 0, connected: 1, pending: 2};

if (match === null) {
	throw 'Cannot find the agent status in the state file.';
}

return (match[1] in states) ? states[match[1]] : 255;`),
        heartbeat("1h"),
      ],
    }),
    dep("Last keep-alive", "wazuh.agent.last_keepalive", "Time of the last keep-alive sent to the manager, in the local time of the agent host.", "health", {
      value_type: "CHAR",
      preprocessing: [regex(field("last_keepalive"), "\\1")],
    }),
    dep("Last ACK", "wazuh.agent.last_ack", "Time of the last control message received from the manager, in the local time of the agent host.", "health", {
      value_type: "CHAR",
      preprocessing: [regex(field("last_ack"), "\\1")],
    }),
    dep("Events generated per second", "wazuh.agent.events.rate", "Events generated by the agent modules.", "events", {
      value_type: "FLOAT",
      units: "eps",
      preprocessing: [regex(field("msg_count"), "\\1"), perSecond()],
    }),
    dep("Messages sent per second", "wazuh.agent.messages.sent.rate", "Messages (events and control messages) sent to the manager.", "events", {
      value_type: "FLOAT",
      units: "mps",
      preprocessing: [regex(field("msg_sent"), "\\1"), perSecond()],
    }),
    dep("Buffered events", "wazuh.agent.buffer.events", "Events waiting in the anti-flooding buffer. No value when the buffer is disabled (<client_buffer><disabled>yes</disabled>).", "events", {
      preprocessing: [regex("msg_buffer='(\\d+)'", "\\1", ["DISCARD_VALUE"])],
    }),
    {
      name: "Version",
      key: VERSION,
      type,
      delay: "1h",
      value_type: "CHAR",
      description: "Version of the Wazuh agent, read from VERSION.json.",
      preprocessing: [jsonpath("$.version"), heartbeat("1d")],
      tags: [["component", "application"]],
    },
  ];

  const triggers: TriggerDef[] = [
    ...DAEMONS.map(
      (d): TriggerDef => ({
        name: `Wazuh agent: Process ${d} is not running`,
        expression: `last(/${T}/proc.num[${d}])=0`,
        priority: d === "wazuh-agentd" ? "HIGH" : "AVERAGE",
        description: `${d} is not running. Check "systemctl status wazuh-agent" and /var/ossec/logs/ossec.log on the host.`,
        depends: d === "wazuh-agentd" ? undefined : ["Wazuh agent: Process wazuh-agentd is not running"],
        scope: "availability",
      }),
    ),
    {
      name: "Wazuh agent: Not connected to the manager",
      event_name: "Wazuh agent: Not connected to the manager (for 5m)",
      expression: `count(/${T}/wazuh.agent.status,5m,"eq","1")=0`,
      opdata: "Status: {ITEM.LASTVALUE1}",
      priority: "AVERAGE",
      description: "The agent was not connected to the manager for 5 minutes. Events are buffered on the host and dropped when the buffer is full. Check the network path to the manager (1514/TCP) and the agent key.",
      depends: ["Wazuh agent: Process wazuh-agentd is not running"],
      scope: "availability",
    },
    {
      name: "Wazuh agent: State file is not updated",
      event_name: "Wazuh agent: State file is not updated (for {$WAZUH.AGENT.STATE.AGE.MAX.WARN})",
      expression: `fuzzytime(/${T}/${STATE_TIME},{$WAZUH.AGENT.STATE.AGE.MAX.WARN})=0`,
      priority: "WARNING",
      description: "wazuh-agentd has not updated its state file. The daemon is hung, or the clock of the host differs from the clock of the Zabbix server.",
      depends: ["Wazuh agent: Process wazuh-agentd is not running"],
      scope: "availability",
    },
    {
      name: "Wazuh agent: Event buffer usage is high",
      event_name: "Wazuh agent: Event buffer usage is high (over {$WAZUH.AGENT.BUFFER.UTIL.MAX.WARN}% for 5m)",
      expression: `min(/${T}/wazuh.agent.buffer.events,5m)>{$WAZUH.AGENT.BUFFER.SIZE}*{$WAZUH.AGENT.BUFFER.UTIL.MAX.WARN}/100`,
      opdata: "Buffered: {ITEM.LASTVALUE1}",
      priority: "WARNING",
      description: "The anti-flooding buffer is filling up. When it is full, new events are dropped. Set {$WAZUH.AGENT.BUFFER.SIZE} to the <client_buffer><queue_size> of the agent.",
      scope: "performance",
    },
    {
      name: "Wazuh agent: Version has changed",
      expression: `last(/${T}/${VERSION},#1)<>last(/${T}/${VERSION},#2) and length(last(/${T}/${VERSION}))>0`,
      priority: "INFO",
      manual_close: true,
      description: "The Wazuh agent version has changed. Acknowledge to close the problem manually.",
      scope: "notice",
    },
  ];

  return {
    name,
    target: "wazuh",
    description: `Monitors a Wazuh agent on Linux with ${type ? "Zabbix agent (active checks)" : "Zabbix agent (passive checks)"}: daemon processes, connection status, event rates and buffer read from the wazuh-agentd state file, and the agent version.

Setup:

1. Give the zabbix user read access to the state file and VERSION.json with POSIX ACLs (package acl):
"setfacl -m u:zabbix:x /var/ossec /var/ossec/var /var/ossec/var/run"
"setfacl -m u:zabbix:r /var/ossec/VERSION.json /var/ossec/var/run/wazuh-agentd.state"
"setfacl -d -m u:zabbix:r /var/ossec /var/ossec/var/run"
The default ACLs keep the access when Wazuh recreates the files. Do not add zabbix to the wazuh group: that group can write ossec.conf, and Wazuh runs the commands configured there as root.
2. Link the template to the host.
3. If the agent is installed outside /var/ossec, change {$WAZUH.AGENT.HOME}. If <client_buffer><queue_size> is changed in ossec.conf, set {$WAZUH.AGENT.BUFFER.SIZE} to the same value.

Works with Zabbix agent and Zabbix agent 2. Tested with Wazuh agent 4.14 and Zabbix 7.0.`,
    macros: [
      { macro: "{$WAZUH.AGENT.HOME}", value: "/var/ossec", description: "Installation directory of the Wazuh agent." },
      { macro: "{$WAZUH.AGENT.BUFFER.SIZE}", value: "5000", description: "Size of the anti-flooding buffer (<client_buffer><queue_size>). The Wazuh default is 5000." },
      { macro: "{$WAZUH.AGENT.BUFFER.UTIL.MAX.WARN}", value: "80", description: "Warning threshold of the anti-flooding buffer usage, in %." },
      { macro: "{$WAZUH.AGENT.STATE.AGE.MAX.WARN}", value: "5m", description: "Maximum age of the wazuh-agentd state file." },
    ],
    valuemaps: [{ name: "Wazuh agent status", map: [["0", "disconnected"], ["1", "connected"], ["2", "pending"], ["255", "unknown"]] }],
    items,
    triggers,
  };
}

export const agent = build(AGENT, undefined);
export const agentActive = build(AGENT_ACTIVE, "ZABBIX_ACTIVE");
